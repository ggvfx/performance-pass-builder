"""
Tests for Source Inspection.

Run against clips generated by ffmpeg in conftest.py, so every number asserted
here is one the file really has. test_fixtures.py checks the clips themselves,
which is what stops these passing for the wrong reason.
"""

import shutil
from pathlib import Path

import pytest

from src.core.ffmpeg_tools import MediaToolchain
from src.media.probe import SourceProbe, suggested_output_dir

needs_ffmpeg = pytest.mark.skipif(
    shutil.which("ffprobe") is None, reason="ffprobe is not installed"
)


@pytest.fixture(scope="module")
def probe() -> SourceProbe:
    return SourceProbe(MediaToolchain())


# --- OUTPUT NAMING ---


def test_deliverables_go_in_a_folder_beside_the_source():
    """
    Worked out with pathlib server-side, which is the point of doing it here:
    minicut's front end split on forward slashes only, so a Windows path never
    split, and it happened to produce the right answer anyway.
    """
    windows = suggested_output_dir(Path(r"D:\footage\take_01.mov"))
    assert windows.name == "take_01_performance"
    assert windows.parent == Path(r"D:\footage")

    posix = suggested_output_dir(Path("/mnt/footage/take_01.mov"))
    assert posix.name == "take_01_performance"


# --- THE RATE ---


@needs_ffmpeg
def test_the_rate_survives_as_an_exact_pair(probe, clips):
    """
    The invariant the project rests on. 24000/1001 must arrive as two
    integers, because 23.976 drifts a frame roughly every forty seconds.
    """
    source = probe.probe(clips["ntsc24"])

    assert (source.fps_numerator, source.fps_denominator) == (24000, 1001)
    assert source.frame_count == 48


@needs_ffmpeg
def test_a_whole_number_rate_is_still_a_rational(probe, clips):
    source = probe.probe(clips["pal25"])

    assert (source.fps_numerator, source.fps_denominator) == (25, 1)
    assert source.frame_count == 50


@needs_ffmpeg
def test_geometry_and_codec_are_read_off_the_file(probe, clips):
    source = probe.probe(clips["film24"])

    assert (source.width, source.height) == (320, 240)
    assert source.codec == "h264"
    assert source.pixel_format == "yuv420p"


@needs_ffmpeg
def test_h265_is_recognised_as_itself(probe, clips):
    """The mezzanine keeps the source's codec, so this is the branch it picks on."""
    assert probe.probe(clips["h265"]).codec == "hevc"


# --- VARIABLE FRAME RATE ---


@needs_ffmpeg
def test_a_variable_frame_rate_source_is_reported(probe, clips):
    """Reported here; refused by `inspect`. This module states what a file is."""
    assert probe.probe(clips["vfr"]).is_variable_frame_rate is True


@needs_ffmpeg
def test_constant_frame_rate_clips_are_not_flagged(probe, clips):
    """A false positive here would refuse perfectly good footage."""
    for name in ("ntsc24", "pal25", "film24", "with_audio", "h265"):
        assert probe.probe(clips[name]).is_variable_frame_rate is False, name


@needs_ffmpeg
def test_inspect_refuses_variable_frame_rate_with_a_reason(probe, clips):
    """
    A refusal, not a warning: there is no stable frame-to-time mapping, so
    every frame of every pass would drift. And it carries its reason, so the
    page can show it rather than surfacing an exception.
    """
    report = probe.inspect(clips["vfr"])

    assert report.can_build is False
    assert "variable frame rate" in report.refusal_reason
    assert "constant frame rate" in report.refusal_reason


@needs_ffmpeg
def test_inspect_allows_a_constant_frame_rate_source(probe, clips):
    report = probe.inspect(clips["ntsc24"])

    assert report.can_build is True
    assert report.refusal_reason is None


# --- AUDIO ---


@needs_ffmpeg
def test_a_mute_source_has_no_audio(probe, clips):
    source = probe.probe(clips["film24"])

    assert source.audio is None
    assert source.has_audio is False


@needs_ffmpeg
def test_aac_can_be_stream_copied(probe, clips):
    """The normal path: carried into the output untouched."""
    source = probe.probe(clips["with_audio"])

    assert source.audio is not None
    assert source.audio.codec == "aac"
    assert source.audio.sample_rate == 48000
    assert source.audio.can_stream_copy_to_mp4 is True


@needs_ffmpeg
def test_pcm_cannot_be_stream_copied_and_the_user_is_told_before_the_job(probe, clips):
    """
    24-bit PCM off a camera is the case mp4 will not take. Learning that from
    the probe rather than from ffmpeg failing at the end of a job is the whole
    reason the field exists — CLAUDE.md non-negotiable 3.
    """
    source = probe.probe(clips["pcm_audio"])

    assert source.audio.codec == "pcm_s24le"
    assert source.audio.can_stream_copy_to_mp4 is False

    report = probe.inspect(clips["pcm_audio"])
    assert report.can_build is True, "a re-encode is a warning, not a refusal"
    assert any("encoded once" in warning for warning in report.warnings)


