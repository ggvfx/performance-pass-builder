# --- THE REPORT ---


@needs_ffmpeg
def test_the_report_shows_a_duration_measured_from_zero(probe, clips):
    """
    A length, not a position. Using the source's own start timecode here would
    report 10:00:02:00 for a two second clip that starts at 10:00:00:00.
    """
    report = probe.inspect(clips["pal25"])

    assert report.duration_timecode == "00:00:02:00"


@needs_ffmpeg
def test_the_report_suggests_where_to_write(probe, clips):
    report = probe.inspect(clips["ntsc24"])

    assert report.suggested_output_dir.name == "ntsc24_performance"


@needs_ffmpeg
def test_the_disk_estimate_scales_with_the_picture(probe, clips):
    """
    Bigger and faster sources cost more, which is the only property worth
    asserting — the figure itself is a rule of thumb, not a measurement.
    """
    small = probe.probe(clips["film24"])
    big = small.model_copy(update={"width": 1920, "height": 1080})

    assert probe.estimate_disk_required(big) > probe.estimate_disk_required(small)
    assert probe.estimate_disk_required(small) > 0


@needs_ffmpeg
def test_free_space_is_only_reported_when_there_is_somewhere_to_measure(probe, clips, tmp_path):
    """None until the user picks an output directory, which is the state on launch."""
    assert probe.inspect(clips["ntsc24"]).free_gb is None
    assert probe.inspect(clips["ntsc24"], output_dir=tmp_path).free_gb > 0
